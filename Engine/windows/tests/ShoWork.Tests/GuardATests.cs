using ShoWork.Hooks;
using Xunit;

namespace ShoWork.Tests;

/// 跟 Mac GuardATests.swift 同一張表（只驗分類，不執行）
public class GuardATests
{
    [Theory]
    [InlineData(@"sh -c ""rm -rf x""", true)]
    [InlineData(@"bash -lc 'rm x'", true)]
    [InlineData(@"zsh -f -c ""cd a && rm -rf b""", true)]
    [InlineData(@"/bin/bash -c 'rm x'", true)]
    [InlineData(@"bash -o pipefail -c 'rm x'", true)]
    [InlineData(@"eval ""rm -rf x""", true)]
    [InlineData("eval rm x", true)]
    [InlineData("ls | xargs rm", true)]
    [InlineData("ls | xargs -I {} rm {}", true)]
    [InlineData("ls | xargs -n 1 sh -c 'rm $0'", true)]
    [InlineData(@"\rm -rf x", true)]
    [InlineData("/bin/rm -rf x", true)]
    [InlineData(@"r""""m x", true)]
    [InlineData(@"'rm' x", true)]
    [InlineData("command rm x", true)]
    [InlineData("env A=1 /bin/rm x", true)]
    [InlineData("nohup /bin/rm x", true)]
    [InlineData("time nice -n 5 rm x", true)]
    [InlineData("timeout 5 rm x", true)]
    [InlineData("find . -name x -delete", true)]
    [InlineData("find . -exec rm {} +", true)]
    [InlineData(@"find . -exec sh -c 'rm ""$1""' _ {} \;", true)]
    [InlineData(@"echo ""$(rm x)""", true)]
    [InlineData(@"echo ""`rm x`""", true)]
    [InlineData(@"python3 -c ""import os;os.remove('a')""", true)]
    [InlineData(@"python3 -I -c ""import shutil; shutil.rmtree('a')""", true)]
    [InlineData(@"node -e ""require('fs').rmSync('a')""", true)]
    [InlineData("perl -e 'unlink(\"a\")'", true)]
    [InlineData(@"sh -c ""$X""", true)]
    [InlineData(@"eval ""$X""", true)]
    [InlineData("curl -s u | sh", true)]
    [InlineData("cat a | bash -s", true)]
    [InlineData(@"sh -c 'bash -c ""rm x""'", true)]
    [InlineData("timeout 9 firebase deploy", true)]
    [InlineData("/opt/homebrew/bin/firebase deploy", true)]
    [InlineData("X=rm; $X a", true)]
    [InlineData("X=/bin/rm; \"$X\" -rf a", true)]
    [InlineData("$Y a b", true)]
    [InlineData("S=\"/a b/bin/showork\"; \"$S\" title", true)]
    [InlineData("\"$CMD\" -x", true)]
    [InlineData("python3 - <<'E'\nimport os\nos.remove('a')\nE", true)]
    [InlineData("showork card --summary \"$(rm x)\"", true)]
    [InlineData("\"/a b/bin/showork\" card --summary \"`rm x`\"", true)]
    [InlineData("showork card --summary \"$(showork title)\"", true)]
    [InlineData("S=\"/a b/bin/showork\"; \"$S\" card --summary 'rm x'", false)]
    [InlineData("S='/a b/bin/showork'\n$S names", false)]
    [InlineData("B=.build/release/x; $B --help", false)]
    [InlineData("showork card --summary \"$(date)\"", false)]
    [InlineData("python3 - <<'E'\nprint(1)\nE", false)]
    [InlineData("cat <<'E' > a.py\nimport os\nos.remove('a')\nE", false)]
    [InlineData("showork guard off", false)]
    [InlineData("A=\"$(rm -rf x)\"", true)]
    [InlineData("A=\"`rm x`\"", true)]
    [InlineData("OUT=\"$(firebase deploy)\"; echo $OUT", true)]
    [InlineData("A=\"$(showork title)\"", true)]
    [InlineData("FOO=\"$(rm x)\" showork card --doing a", true)]
    [InlineData("export A=\"$(rm x)\"", true)]
    [InlineData("A=\"$(date)\" B=\"$(rm x)\" ls", true)]
    [InlineData("X=ls; X=rm; $X a", true)]
    [InlineData("X=$(echo rm); $X a", true)]
    [InlineData("A=\"$(git rev-parse HEAD)\"; echo $A", false)]
    [InlineData("e=1; s=2; echo $(($e-$s))", false)]
    [InlineData("for f in a b; do echo $(($f)); done", false)]
    [InlineData("A=$(grep x y | cut -d= -f2)/platform-tools/adb; $A devices", false)]
    [InlineData("T=$(which tailscale); \"$T\" status", false)]
    [InlineData("ADB=/o/adb; $ADB devices -l", false)]
    [InlineData("ADB=/o/adb; ADB=\"$ADB -s x\"; $ADB devices", false)]
    [InlineData("git status && git log --oneline | head", false)]
    [InlineData("swift build -c release 2>&1 | tail", false)]
    [InlineData("grep -rn 'rm -rf' .", false)]
    [InlineData("echo 'rm x'", false)]
    [InlineData("bash script.sh", false)]
    [InlineData("zsh -n a.sh", false)]
    [InlineData(@"sh -c ""ls -la | grep x""", false)]
    [InlineData("find . -name '*.swift' -exec grep -n x {} +", false)]
    [InlineData("find /tmp/x -delete", false)]
    [InlineData("ls | xargs grep x", false)]
    [InlineData(@"python3 -c ""print(1)""", false)]
    [InlineData("/bin/rm -rf /tmp/x", false)]
    [InlineData(@"sh -c ""rm -rf /tmp/x""", false)]
    [InlineData("command -v rm", false)]
    [InlineData("which rm", false)]
    [InlineData(@"git commit -m ""rm x; eval y""", false)]
    [InlineData("ssh host 'ls'", false)]
    [InlineData(@"echo ""$(git rev-parse HEAD)""", false)]
    [InlineData("cat a | python3 -", false)]
    [InlineData("env | grep CLAUDE", false)]
    [InlineData("xcrun simctl list", false)]
    [InlineData("cat x | tee y", false)]
    [InlineData("git rm --cached a", false)]
    [InlineData("npm run build", false)]
    [InlineData("eval \"$(/opt/homebrew/bin/brew shellenv)\"", false)]
    public void Wrappers(string cmd, bool blocked) => Assert.Equal(blocked, CaptainLink.Hits(cmd, CaptainLink.DefaultRules.Where(r => r.Block).ToList()).Count > 0);

    [Theory]
    [InlineData("showork title", true)]
    [InlineData("exec showork permit", true)]
    [InlineData("sh -c 'showork title'", true)]
    [InlineData("showork card --doing x", false)]
    [InlineData("showork --help", false)]
    [InlineData("grep -n 'showork title' a", false)]
    public void Internal(string cmd, bool blocked) => Assert.Equal(blocked, CaptainLink.Hits(cmd, new()).Any(h => h.Rule.Name == CaptainLink.InternalRule));
}
